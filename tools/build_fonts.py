#!/usr/bin/env python3
"""Instance + subset the two OFL variable fonts into small woff2 files and
emit shared/fonts.css: @font-face rules with base64 data URIs that every SVG
pastes into its <style>. Run with the project venv:  .venv/bin/python tools/build_fonts.py
"""
import base64
import io
import pathlib
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont
from fontTools import subset

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "_source" / "fonts_dl"
OUT = ROOT / "shared"
OUT.mkdir(exist_ok=True)

# printable ASCII + the few typographic glyphs the cards use
TEXT = "".join(chr(c) for c in range(0x20, 0x7F)) + "—–·•…’‘“”→←↗↑↓★✦✓×°©®™"

FACES = [
    # family name used in CSS, source, axis location, weight label
    ("Brico Display", "brico.ttf", {"wght": 800, "opsz": 72, "wdth": 100}, 800),
    ("Brico", "brico.ttf", {"wght": 500, "opsz": 14, "wdth": 100}, 500),
    ("JBM", "jbm.ttf", {"wght": 500}, 500),
    ("JBM", "jbm.ttf", {"wght": 700}, 700),
]


def build(src, loc):
    font = TTFont(SRC / src)
    font = instantiateVariableFont(font, loc)
    opts = subset.Options()
    opts.flavor = "woff2"
    opts.layout_features = ["kern", "liga", "calt"]
    opts.name_IDs = ["*"]
    opts.notdef_outline = True
    sub = subset.Subsetter(opts)
    sub.populate(text=TEXT)
    sub.subset(font)
    buf = io.BytesIO()
    font.flavor = "woff2"
    font.save(buf)
    return buf.getvalue()


css = ["/* generated by tools/build_fonts.py — Bricolage Grotesque + JetBrains Mono, SIL OFL 1.1 */"]
for family, src, loc, weight in FACES:
    data = build(src, loc)
    b64 = base64.b64encode(data).decode()
    print(f"{family} {weight}: {len(data)/1024:.1f} KB woff2, {len(b64)/1024:.1f} KB base64")
    css.append(
        f"@font-face{{font-family:'{family}';font-weight:{weight};font-style:normal;"
        f"src:url(data:font/woff2;base64,{b64}) format('woff2');}}"
    )
(OUT / "fonts.css").write_text("\n".join(css) + "\n")
print("wrote", OUT / "fonts.css", f"{(OUT / 'fonts.css').stat().st_size/1024:.1f} KB")
